using System.Text;
using DevStackStudio.Core.Contracts;
using DevStackStudio.Core.Models;
using DevStackStudio.Core.Providers;

namespace DevStackStudio.Generators.Schema;

public sealed class SchemaSqlGenerator
{
    public GeneratedFile Generate(ProjectConfiguration configuration)
    {
        var provider = DatabaseProviderCatalog.Default.Get(configuration.Database.Engine);
        var sql = new StringBuilder();
        sql.AppendLine("-- Generated by DevStack Studio. Identifiers are quoted; values are escaped literals only.");
        sql.AppendLine("-- EF Core migrations are the primary evolution mechanism for the .NET backend.");
        sql.AppendLine();

        foreach (var entity in configuration.Entities.OrderBy(e => e.Name, StringComparer.Ordinal))
        {
            sql.Append("CREATE TABLE ");
            sql.Append(provider.QuoteIdentifier(entity.Name));
            sql.AppendLine(" (");
            var columnSql = entity.Columns.OrderBy(c => c.Ordinal).Select(c => ColumnSql(c, entity, provider, configuration)).ToList();
            sql.AppendLine(string.Join("," + Environment.NewLine, columnSql));
            sql.AppendLine(");");
            sql.AppendLine();

            foreach (var column in entity.Columns.Where(c => c.HasIndex && !c.IsPrimaryKey && !c.IsUnique))
            {
                sql.Append("CREATE INDEX ");
                sql.Append(provider.QuoteIdentifier($"IX_{entity.Name}_{column.Name}"));
                sql.Append(" ON ");
                sql.Append(provider.QuoteIdentifier(entity.Name));
                sql.Append(" (");
                sql.Append(provider.QuoteIdentifier(column.Name));
                sql.AppendLine(");");
            }
        }

        foreach (var relationship in configuration.Relationships.Where(r => r.Kind == RelationshipKind.ManyToMany))
        {
            var join = string.IsNullOrWhiteSpace(relationship.JoinTableName) ? relationship.Name + "Link" : relationship.JoinTableName;
            var from = configuration.Entities.Single(e => e.Id == relationship.FromEntityId);
            var to = configuration.Entities.Single(e => e.Id == relationship.ToEntityId);
            var fromPk = from.Columns.Single(c => c.Id == relationship.FromColumnId);
            var toPk = to.Columns.Single(c => c.Id == relationship.ToColumnId);
            sql.Append("CREATE TABLE ");
            sql.Append(provider.QuoteIdentifier(join));
            sql.AppendLine(" (");
            sql.Append("  ");
            sql.Append(provider.QuoteIdentifier(from.Name + "Id"));
            sql.Append(' ');
            sql.Append(provider.GetType(fromPk.LogicalType)!.ProviderTypeName);
            sql.Append(" NOT NULL,");
            sql.AppendLine();
            sql.Append("  ");
            sql.Append(provider.QuoteIdentifier(to.Name + "Id"));
            sql.Append(' ');
            sql.Append(provider.GetType(toPk.LogicalType)!.ProviderTypeName);
            sql.AppendLine(" NOT NULL");
            sql.AppendLine(");");
        }

        return new GeneratedFile
        {
            RelativePath = "database/schema.sql",
            Contents = sql.ToString()
        };
    }

    private static string ColumnSql(ColumnDefinition column, EntityDefinition entity, IDatabaseProvider provider, ProjectConfiguration configuration)
    {
        var type = provider.GetType(column.LogicalType) ?? throw new InvalidOperationException(column.LogicalType);
        var typeName = type.ProviderTypeName;
        if (type.SupportsLength && column.Length is int length && !typeName.Contains('(', StringComparison.Ordinal))
        {
            typeName += "(" + length + ")";
        }
        else if (type.SupportsPrecision && column.Precision is int precision)
        {
            typeName += "(" + precision + "," + (column.Scale ?? 0) + ")";
        }

        var builder = new StringBuilder("  ");
        builder.Append(provider.QuoteIdentifier(column.Name));
        builder.Append(' ');
        builder.Append(typeName);
        builder.Append(column.IsNullable ? " NULL" : " NOT NULL");
        if (column.IsPrimaryKey)
        {
            builder.Append(" PRIMARY KEY");
        }

        if (column.Identity == IdentityStrategy.DatabaseIdentity && configuration.Database.Engine is DatabaseEngine.SqlServer)
        {
            builder.Append(" IDENTITY(1,1)");
        }

        if (column.Identity == IdentityStrategy.DatabaseIdentity && configuration.Database.Engine is DatabaseEngine.PostgreSql && column.LogicalType is "int" or "bigint")
        {
            // SERIAL-style identity
            builder.Append(" GENERATED BY DEFAULT AS IDENTITY");
        }

        if (column.IsUnique && !column.IsPrimaryKey)
        {
            builder.Append(" UNIQUE");
        }

        var defaultSql = provider.FormatDefault(column, type);
        if (!string.IsNullOrEmpty(defaultSql))
        {
            builder.Append(" DEFAULT ");
            builder.Append(defaultSql);
        }

        if (column.ForeignKeyTargetEntityId is Guid targetEntityId)
        {
            var target = configuration.Entities.Single(e => e.Id == targetEntityId);
            var targetColumn = target.Columns.Single(c => c.Id == column.ForeignKeyTargetColumnId);
            builder.Append(" REFERENCES ");
            builder.Append(provider.QuoteIdentifier(target.Name));
            builder.Append(" (");
            builder.Append(provider.QuoteIdentifier(targetColumn.Name));
            builder.Append(')');
            builder.Append(" ON DELETE ");
            builder.Append(column.OnDelete switch
            {
                ForeignKeyDeleteBehavior.Cascade => "CASCADE",
                ForeignKeyDeleteBehavior.SetNull => "SET NULL",
                ForeignKeyDeleteBehavior.NoAction => "NO ACTION",
                _ => "RESTRICT"
            });
        }

        return builder.ToString();
    }
}
