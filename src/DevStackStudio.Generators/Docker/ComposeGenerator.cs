using System.Text;
using DevStackStudio.Core.Contracts;
using DevStackStudio.Core.Models;
using DevStackStudio.Core.Providers;

namespace DevStackStudio.Generators.Docker;

public sealed class ComposeGenerator
{
    public IReadOnlyList<GeneratedFile> Generate(ProjectConfiguration configuration)
    {
        var provider = DatabaseProviderCatalog.Default.Get(configuration.Database.Engine);
        var bind = configuration.Database.PortBinding == PortBindingMode.Localhost ? "127.0.0.1:" : string.Empty;
        var image = $"{provider.Metadata.ImageName}:{configuration.Database.ImageTag}";
        if (string.IsNullOrWhiteSpace(configuration.Database.ImageTag))
        {
            image = $"{provider.Metadata.ImageName}:{provider.Metadata.ImageTag}";
        }

        var volumePath = configuration.Database.Engine switch
        {
            DatabaseEngine.MySql => "/var/lib/mysql",
            DatabaseEngine.SqlServer => "/var/opt/mssql",
            DatabaseEngine.Oracle => "/opt/oracle/oradata",
            _ => "/var/lib/postgresql/data"
        };

        var volumeEntries = new StringBuilder();
        volumeEntries.AppendLine($"      - db_data:{volumePath}");
        if (configuration.Database.Engine == DatabaseEngine.Oracle)
        {
            volumeEntries.AppendLine("      - ./database/init-oracle.sql:/opt/oracle/scripts/startup/01-init.sql:ro");
        }

        var envLines = new StringBuilder();
        foreach (var pair in provider.BuildEnvironmentVariables(configuration.Database))
        {
            envLines.AppendLine($"      {pair.Key}: {pair.Value}");
        }

        var backendCs = configuration.Database.Engine switch
        {
            DatabaseEngine.PostgreSql => $"Host=db;Port={provider.Metadata.DefaultPort};Database={configuration.Database.DatabaseName};Username={configuration.Database.Username};Password=${{DB_PASSWORD}}",
            DatabaseEngine.MySql => $"Server=db;Port={provider.Metadata.DefaultPort};Database={configuration.Database.DatabaseName};User={configuration.Database.Username};Password=${{DB_PASSWORD}}",
            DatabaseEngine.SqlServer => $"Server=db,{provider.Metadata.DefaultPort};Database={configuration.Database.DatabaseName};User Id={configuration.Database.Username};Password=${{DB_PASSWORD}};TrustServerCertificate=True",
            DatabaseEngine.Oracle => $"User Id={configuration.Database.Username};Password=${{DB_PASSWORD}};Data Source=db:{provider.Metadata.DefaultPort}/{OracleProvider.ResolveServiceName(configuration.Database.DatabaseName)}",
            _ => throw new InvalidOperationException()
        };

        var compose = $"""
            # Generated by DevStack Studio. Credentials come from `.env`, not this file.
            name: {configuration.Docker.ComposeProjectName}
            services:
              db:
                image: {image}
                container_name: {configuration.Database.ContainerName}
                restart: {configuration.Database.RestartPolicy}
                environment:
            {envLines.ToString().TrimEnd()}
                ports:
                  - "{bind}{configuration.Database.HostPort}:{provider.Metadata.DefaultPort}"
                volumes:
            {volumeEntries.ToString().TrimEnd()}
                healthcheck:
                  test: ["CMD-SHELL", "{Escape(provider.BuildHealthcheckTest(configuration.Database))}"]
                  interval: 10s
                  timeout: 10s
                  retries: 30
                  start_period: 45s
                networks:
                  - appnet
              backend:
                build:
                  context: ./backend
                  dockerfile: Dockerfile
                container_name: {configuration.Docker.ComposeProjectName}-api
                restart: unless-stopped
                environment:
                  ASPNETCORE_ENVIRONMENT: Development
                  ASPNETCORE_URLS: http://0.0.0.0:8080
                  DefaultConnection: {backendCs}
                  ConnectionStrings__Default: {backendCs}
                  Database__ApplyMigrations: "true"
                ports:
                  - "{bind}{configuration.Docker.BackendHostPort}:8080"
                depends_on:
                  db:
                    condition: service_healthy
                networks:
                  - appnet
              frontend:
                build:
                  context: ./frontend
                  dockerfile: Dockerfile
                  args:
                    NEXT_PUBLIC_API_URL: http://localhost:{configuration.Docker.BackendHostPort}
                container_name: {configuration.Docker.ComposeProjectName}-web
                restart: unless-stopped
                environment:
                  NEXT_PUBLIC_API_URL: http://localhost:{configuration.Docker.BackendHostPort}
                ports:
                  - "{bind}{configuration.Docker.FrontendHostPort}:3000"
                depends_on:
                  backend:
                    condition: service_started
                networks:
                  - appnet

            networks:
              appnet:
                name: {configuration.Docker.NetworkName}

            volumes:
              db_data:
                name: {configuration.Database.VolumeName}
            """;

        var prod = $"""
            # Production-oriented overlay. Does not mount source. Still expects secrets via environment, not image layers.
            name: {configuration.Docker.ComposeProjectName}
            services:
              backend:
                environment:
                  ASPNETCORE_ENVIRONMENT: Production
                  Database__ApplyMigrations: "false"
              frontend:
                environment:
                  NODE_ENV: production
            """;

        return
        [
            new GeneratedFile { RelativePath = "docker-compose.yml", Contents = compose + Environment.NewLine },
            new GeneratedFile { RelativePath = "docker-compose.prod.yml", Contents = prod + Environment.NewLine }
        ];
    }

    private static string Escape(string value) => value.Replace("\"", "\\\"", StringComparison.Ordinal);
}
