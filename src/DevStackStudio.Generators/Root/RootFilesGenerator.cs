using System.Text.Json;

using DevStackStudio.Core.Contracts;

using DevStackStudio.Core.Models;

using DevStackStudio.Core.Naming;

using DevStackStudio.Core.Providers;

using DevStackStudio.Core.Serialization;



namespace DevStackStudio.Generators.Root;



public sealed class RootFilesGenerator

{

    public IReadOnlyList<GeneratedFile> Generate(ProjectConfiguration configuration)

    {

        var provider = DatabaseProviderCatalog.Default.Get(configuration.Database.Engine);

        var ns = NameFactory.CSharpNamespace(configuration.ProjectName);

        var envExample = """

            # Copy to `.env` and set real values. `.env` is gitignored.

            # Environment variables are visible to users with Docker or host access. This is not a vault.

            COMPOSE_PROJECT_NAME=PROJECT

            DB_PASSWORD=change-me

            DB_ROOT_PASSWORD=change-me-root

            """.Replace("PROJECT", configuration.Docker.ComposeProjectName, StringComparison.Ordinal);



        var env = $"""

            COMPOSE_PROJECT_NAME={configuration.Docker.ComposeProjectName}

            DB_PASSWORD={configuration.Database.Password}

            DB_ROOT_PASSWORD={configuration.Database.Password}

            """;



        var gitignore = """

            bin/

            obj/

            .vs/

            .idea/

            node_modules/

            .next/

            dist/

            .env

            .env.local

            *.user

            TestResults/

            artifacts/

            """;



        var readme = $"""

            # {configuration.ProjectName}



            Generated by DevStack Studio {TemplateCatalog.Version}. This is a normal source-code project. DevStack Studio is not required after generation.



            ## Stack



            - Database: {provider.Metadata.DisplayName} (`{provider.Metadata.ImageName}:{provider.Metadata.ImageTag}`)

            - Backend: ASP.NET Core CQRS on .NET 10 (`backend/`)

            - Frontend: Next.js TypeScript (`frontend/`)

            - Orchestration: Docker Compose



            ## Secrets



            Copy `.env.example` to `.env`. Compose reads `DB_PASSWORD` from `.env`. Credentials are not baked into images or committed to git.



            ## Commands



            ```bash

            docker compose up --build -d

            docker compose ps

            docker compose logs -f

            docker compose restart

            docker compose down              # keeps the named volume

            docker compose down -v           # DELETES database data — requires intent

            docker compose exec backend sh

            ```



            Backend migrations run on API startup when `Database__ApplyMigrations=true` (development Compose). They do not drop existing data.



            Frontend talks to the API at `NEXT_PUBLIC_API_URL` (browser URL, default `http://localhost:{configuration.Docker.BackendHostPort}`). Inside Compose, the API reaches the database at hostname `db`, not `localhost`.



            ## License notes



            {provider.Metadata.LicenseSummary}

            """;



        var configJson = ProjectConfigurationSerializer.Serialize(configuration);

        var schemaJson = JsonSerializer.Serialize(new

        {

            project = configuration.ProjectName,

            engine = configuration.Database.Engine.ToString(),

            entities = configuration.Entities.Select(e => new

            {

                e.Name,

                columns = e.Columns.Select(c => new { c.Name, c.LogicalType, c.IsPrimaryKey, c.IsNullable })

            })

        }, ProjectConfigurationSerializer.Options);



        var makefile = """

            .PHONY: up down logs ps rebuild test-backend

            up:

            	docker compose up --build -d

            down:

            	docker compose down

            logs:

            	docker compose logs -f

            ps:

            	docker compose ps

            rebuild:

            	docker compose build --no-cache

            test-backend:

            	dotnet test backend

            """;



        var files = new List<GeneratedFile>

        {

            new GeneratedFile { RelativePath = ".env.example", Contents = envExample + Environment.NewLine },

            new GeneratedFile { RelativePath = ".env", Contents = env + Environment.NewLine, IsSecret = true },

            new GeneratedFile { RelativePath = ".gitignore", Contents = gitignore + Environment.NewLine },

            new GeneratedFile { RelativePath = "README.md", Contents = readme + Environment.NewLine },

            new GeneratedFile { RelativePath = "devstack-project.json", Contents = configJson + Environment.NewLine },

            new GeneratedFile { RelativePath = "database/schema.manifest.json", Contents = schemaJson + Environment.NewLine },

            new GeneratedFile { RelativePath = "Makefile", Contents = makefile + Environment.NewLine },

            new GeneratedFile { RelativePath = "backend/" + ns + ".slnx", Contents = $"""

                <Solution>

                  <Project Path="Api/Api.csproj" />

                  <Project Path="Models/Models.csproj" />

                  <Project Path="Repository/Repository.csproj" />

                  <Project Path="Services/Services.csproj" />

                  <Project Path="SharedRepository/SharedRepository.csproj" />

                  <Project Path="SharedWeb/SharedWeb.csproj" />

                  <Project Path="UnitTests/UnitTests.csproj" />

                </Solution>

                """ + Environment.NewLine }

        };



        if (configuration.Database.Engine == DatabaseEngine.Oracle)
        {
            var dbName = configuration.Database.DatabaseName;
            var serviceCreationBlock = (!string.IsNullOrWhiteSpace(dbName) &&
                !dbName.Equals("FREE", StringComparison.OrdinalIgnoreCase) &&
                !dbName.Equals("FREEPDB1", StringComparison.OrdinalIgnoreCase))
                ? $"""

                -- Register custom database name as an active Oracle Service inside FREEPDB1
                DECLARE
                    svc_count NUMBER;
                BEGIN
                    SELECT COUNT(*) INTO svc_count FROM dba_services WHERE name = '{dbName}';
                    IF svc_count = 0 THEN
                        DBMS_SERVICE.CREATE_SERVICE('{dbName}', '{dbName}');
                    END IF;
                    BEGIN
                        DBMS_SERVICE.START_SERVICE('{dbName}');
                    EXCEPTION
                        WHEN OTHERS THEN
                            IF SQLCODE != -44305 THEN
                                RAISE;
                            END IF;
                    END;
                END;
                /
                """
                : string.Empty;

            var initSql = $"""
                -- Generated by DevStack Studio for Oracle Database Free
                ALTER SESSION SET CONTAINER = FREEPDB1;
                {serviceCreationBlock}
                DECLARE
                    user_count NUMBER;
                BEGIN
                    SELECT COUNT(*) INTO user_count FROM all_users WHERE username = UPPER('{configuration.Database.Username}');
                    IF user_count = 0 THEN
                        EXECUTE IMMEDIATE 'CREATE USER {configuration.Database.Username.ToUpperInvariant()} IDENTIFIED BY "{configuration.Database.Password}"';
                        EXECUTE IMMEDIATE 'GRANT CONNECT, RESOURCE, DBA TO {configuration.Database.Username.ToUpperInvariant()}';
                        EXECUTE IMMEDIATE 'ALTER USER {configuration.Database.Username.ToUpperInvariant()} QUOTA UNLIMITED ON USERS';
                    ELSE
                        EXECUTE IMMEDIATE 'ALTER USER {configuration.Database.Username.ToUpperInvariant()} IDENTIFIED BY "{configuration.Database.Password}"';
                        EXECUTE IMMEDIATE 'ALTER USER {configuration.Database.Username.ToUpperInvariant()} ACCOUNT UNLOCK';
                    END IF;
                END;
                /
                """;
            files.Add(new GeneratedFile { RelativePath = "database/init-oracle.sql", Contents = initSql + Environment.NewLine });
        }



        return files;

    }

}

