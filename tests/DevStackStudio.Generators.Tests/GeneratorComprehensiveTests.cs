    [Fact]
    public async Task ProjectGenerator_removes_deleted_entity_files_on_regeneration()
    {
        var tempDir = Path.Combine(Path.GetTempPath(), "DevStackCleanupTest_" + Guid.NewGuid().ToString("N"));
        try
        {
            var config = SampleProjects.CatalogPostgres();
            config.OutputDirectory = tempDir;
            config.Options.DryRun = false;

            var generator = new ProjectGenerator();
            var result1 = await generator.GenerateAsync(config);
            Assert.True(result1.Succeeded);

            var categoryModelPath = Path.Combine(tempDir, "backend", "Models", "Entities", "Category.cs");
            Assert.True(File.Exists(categoryModelPath));

            // Now remove Category from entities (also remove relationship and FK in Product to be valid)
            config.Entities.RemoveAll(e => e.Name == "Category");
            config.Relationships.Clear();
            var product = config.Entities.First(e => e.Name == "Product");
            product.Columns.RemoveAll(c => c.Name == "CategoryId");

            var result2 = await generator.GenerateAsync(config);
            Assert.True(result2.Succeeded);

            // Stale Category file should now be deleted from disk
            Assert.False(File.Exists(categoryModelPath), "Category.cs should have been removed from disk when entity was removed.");
        }
        finally
        {
            if (Directory.Exists(tempDir))
            {
                try { Directory.Delete(tempDir, true); } catch { }
            }
        }
    }
    [Fact]
    public void NextJsFrontendGenerator_does_not_duplicate_lowercase_column_identifiers()
    {
        var config = SampleProjects.CatalogPostgres();
        var entity = new EntityDefinition
        {
            Name = "Abc",
            Columns =
            [
                new ColumnDefinition { Name = "id", LogicalType = "string", IsPrimaryKey = true, Identity = IdentityStrategy.None },
                new ColumnDefinition { Name = "def", LogicalType = "string", IsNullable = false }
            ]
        };
        config.Entities.Add(entity);

        var generator = new NextJsFrontendGenerator();
        var files = generator.Generate(config);

        var apiFile = files.First(f => f.RelativePath == "frontend/lib/api.ts");
        Assert.Contains("export type Abc = { id?: string; def?: string };", apiFile.Contents);
        Assert.DoesNotContain("def?: string; def?: string", apiFile.Contents);
    }
