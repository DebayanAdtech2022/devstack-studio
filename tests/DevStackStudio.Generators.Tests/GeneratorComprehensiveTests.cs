    [Fact]
    public async Task ProjectGenerator_generates_all_expected_files_in_dry_run()
    {
        var config = SampleProjects.CatalogPostgres();
        config.Options.DryRun = true;
        config.OutputDirectory = "C:\\dummy\\output";

        var generator = new ProjectGenerator();
        var result = await generator.GenerateAsync(config);

        Assert.True(result.Succeeded);
        Assert.True(result.DryRun);
        Assert.NotEmpty(result.Files);

        // Core files check
        Assert.Contains(result.Files, f => f.RelativePath == "docker-compose.yml");
        Assert.Contains(result.Files, f => f.RelativePath == ".env.example");
        Assert.Contains(result.Files, f => f.RelativePath == ".gitignore");
        Assert.Contains(result.Files, f => f.RelativePath == "README.md");
        Assert.Contains(result.Files, f => f.RelativePath == "devstack-project.json");
        Assert.Contains(result.Files, f => f.RelativePath == "devstack-manifest.json");

        // Schema sql file
        Assert.Contains(result.Files, f => f.RelativePath == "database/schema.sql");

        // Backend files check
        Assert.Contains(result.Files, f => f.RelativePath.EndsWith(".slnx", StringComparison.OrdinalIgnoreCase) || f.RelativePath.EndsWith(".sln", StringComparison.OrdinalIgnoreCase));
        Assert.Contains(result.Files, f => f.RelativePath.Contains("Controllers/ProductsController.cs"));
        Assert.Contains(result.Files, f => f.RelativePath.Contains("Commands/Create/CommandModel.cs") || f.RelativePath.Contains("Commands/CreateProductCommand.cs"));
        Assert.Contains(result.Files, f => f.RelativePath.Contains("Queries/GetById/QueryModel.cs") || f.RelativePath.Contains("Queries/GetProductByIdQuery.cs"));
        Assert.Contains(result.Files, f => f.RelativePath.Contains("Queries/List/QueryModel.cs") || f.RelativePath.Contains("Queries/ListProductsQuery.cs"));
        Assert.Contains(result.Files, f => f.RelativePath.Contains("AppDbContext.cs"));

        // Frontend files check
        Assert.Contains(result.Files, f => f.RelativePath == "frontend/package.json");
        Assert.Contains(result.Files, f => f.RelativePath == "frontend/Dockerfile");
        Assert.Contains(result.Files, f => f.RelativePath == "frontend/lib/api.ts");
        Assert.Contains(result.Files, f => f.RelativePath.Contains("products/page.tsx"));
    }

    [Theory]
    [InlineData(DatabaseEngine.PostgreSql)]
    [InlineData(DatabaseEngine.MySql)]
    [InlineData(DatabaseEngine.SqlServer)]
    [InlineData(DatabaseEngine.Oracle)]
    public void SchemaSqlGenerator_emits_valid_sql_for_each_provider(DatabaseEngine engine)
    {
        var config = SampleProjects.CatalogPostgres();
        config.Database.Engine = engine;
        config.Database.AcceptProviderLicense = true;

        var generator = new SchemaSqlGenerator();
        var file = generator.Generate(config);

        Assert.Equal("database/schema.sql", file.RelativePath);
        Assert.False(string.IsNullOrWhiteSpace(file.Contents));
        Assert.Contains("Product", file.Contents);
        Assert.Contains("Category", file.Contents);
    }

    [Theory]
    [InlineData(DatabaseEngine.PostgreSql)]
    [InlineData(DatabaseEngine.MySql)]
    [InlineData(DatabaseEngine.SqlServer)]
    [InlineData(DatabaseEngine.Oracle)]
    public void ComposeGenerator_emits_valid_services_and_volumes(DatabaseEngine engine)
    {
        var config = SampleProjects.CatalogPostgres();
        config.Database.Engine = engine;
        config.Database.AcceptProviderLicense = true;

        var generator = new ComposeGenerator();
        var files = generator.Generate(config);

        var composeFile = files.First(f => f.RelativePath == "docker-compose.yml");
        Assert.Contains("services:", composeFile.Contents);
        Assert.Contains("db:", composeFile.Contents);
        Assert.Contains("backend:", composeFile.Contents);
        Assert.Contains("frontend:", composeFile.Contents);
        Assert.Contains("volumes:", composeFile.Contents);
        Assert.Contains("networks:", composeFile.Contents);

        // Env example is generated by RootFilesGenerator, verify RootFilesGenerator produces it
        var rootFiles = new RootFilesGenerator().Generate(config);
        var envExample = rootFiles.First(f => f.RelativePath == ".env.example");
        Assert.Contains("DB_PASSWORD=", envExample.Contents);
    }

